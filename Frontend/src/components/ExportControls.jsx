import { useState } from 'react';
import { exportAnswer, exportHistory, IS_MOCK } from '../services/api.js';
import { downloadBlob } from '../utils/exporters.js';
import Notice from './Notice.jsx';

const FORMATS = [
  { id: 'json', label: 'JSON' },
  { id: 'csv', label: 'CSV' },
  { id: 'xlsx', label: 'Excel (.xlsx)' },
];

// scope="answer" exports one record (needs recordId); scope="history" exports all records.
export default function ExportControls({ scope, recordId, disabled }) {
  const [busy, setBusy] = useState('');
  const [message, setMessage] = useState(null);
  const noun = scope === 'answer' ? 'this answer' : 'all history';

  async function handleExport(format) {
    setBusy(format);
    setMessage(null);
    try {
      const { blob, filename } = scope === 'answer' ? await exportAnswer(recordId, format) : await exportHistory(format);
      downloadBlob(blob, filename);
      setMessage({ kind: 'success', text: `File created and download started: ${filename}` });
    } catch (err) {
      setMessage({ kind: 'error', text: `Export failed: ${err.message}` });
    } finally {
      setBusy('');
    }
  }

  return (
    <div className="export">
      <div className="btn-row" role="group" aria-label={`Export ${noun}`}>
        <span className="export-label">Export {noun}:</span>
        {FORMATS.map((f) => (
          <button key={f.id} type="button" className="btn btn-small" disabled={disabled || Boolean(busy)} onClick={() => handleExport(f.id)}>
            {busy === f.id ? 'Preparing…' : f.label}
          </button>
        ))}
      </div>
      <p className="hint">
        {IS_MOCK
          ? 'Mock mode: the file is created in your browser from simulated records. Server-generated exports arrive with the backend.'
          : 'The file is generated by the backend and downloaded by this page.'}
      </p>
      {message && <Notice kind={message.kind}>{message.text}</Notice>}
    </div>
  );
}
